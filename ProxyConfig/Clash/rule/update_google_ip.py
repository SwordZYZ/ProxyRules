"""Generate Clash, Loon and Quantumult X rule lists from Google's IP ranges."""

import ipaddress
import json
import re
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path
from tempfile import TemporaryDirectory
from urllib.request import urlopen


SOURCE_URL = "https://www.gstatic.com/ipranges/goog.json"
PROXY_CONFIG = Path(__file__).resolve().parents[2]
BEIJING_TIME = timezone(timedelta(hours=8))
UPDATED_LINE = re.compile(rb"^# UPDATED: \d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\n", re.MULTILINE)


def parse_networks(data):
    prefixes = data.get("prefixes") if isinstance(data, dict) else None
    if not isinstance(prefixes, list):
        raise ValueError("Google's feed must contain a prefixes list")

    networks = {4: set(), 6: set()}
    for entry in prefixes:
        if not isinstance(entry, dict):
            raise ValueError(f"Invalid prefix entry: {entry!r}")
        fields = {"ipv4Prefix", "ipv6Prefix"}.intersection(entry)
        if len(fields) != 1:
            raise ValueError(f"Expected one IP prefix per entry: {entry!r}")

        field = fields.pop()
        version = 4 if field == "ipv4Prefix" else 6
        prefix = entry[field]
        if not isinstance(prefix, str) or "/" not in prefix:
            raise ValueError(f"Expected a CIDR for {field}: {prefix!r}")
        network = ipaddress.ip_network(prefix)
        if network.version != version:
            raise ValueError(f"Address family does not match {field}: {prefix}")
        networks[version].add(network)

    ipv4, ipv6 = sorted(networks[4]), sorted(networks[6])
    if not ipv4 or not ipv6:
        raise ValueError("Google's feed must contain both IPv4 and IPv6 ranges")
    return ipv4, ipv6


def render_rules(ipv4, ipv6, ipv4_rule, ipv6_rule, parameter, updated_at):
    lines = [
        "# NAME: GoogleIP",
        "# AUTHOR: github-actions[bot]",
        "# REPO: https://github.com/SwordZYZ/ProxyRules",
        f"# UPDATED: {updated_at}",
        f"# SOURCE: {SOURCE_URL}",
        "# GENERATED BY: update_google_ip.py",
        f"# {ipv4_rule.upper()}: {len(ipv4)}",
        f"# {ipv6_rule.upper()}: {len(ipv6)}",
        f"# TOTAL: {len(ipv4) + len(ipv6)}",
    ]
    lines.extend(f"{ipv4_rule},{network},{parameter}" for network in ipv4)
    lines.extend(f"{ipv6_rule},{network},{parameter}" for network in ipv6)
    return ("\n".join(lines) + "\n").encode("utf-8")


def write_rules(relative_path, content):
    rule_file = PROXY_CONFIG / relative_path
    if rule_file.exists():
        previous, timestamp_count = UPDATED_LINE.subn(b"", rule_file.read_bytes())
        if timestamp_count == 1 and previous == UPDATED_LINE.sub(b"", content):
            print(f"{relative_path} is up to date")
            return

    with TemporaryDirectory(dir=rule_file.parent) as directory:
        temporary_path = Path(directory) / rule_file.name
        temporary_path.write_bytes(content)
        temporary_path.replace(rule_file)
    print(f"Updated {relative_path}")


def update_rules():
    with urlopen(SOURCE_URL, timeout=30) as response:
        ipv4, ipv6 = parse_networks(json.load(response))

    updated_at = datetime.now(BEIJING_TIME).strftime("%Y-%m-%d %H:%M:%S")
    clash_and_loon = render_rules(ipv4, ipv6, "IP-CIDR", "IP-CIDR6", "no-resolve", updated_at)
    quantumult_x = render_rules(ipv4, ipv6, "ip-cidr", "ip6-cidr", "proxy", updated_at)
    write_rules("Clash/rule/GoogleIP.list", clash_and_loon)
    write_rules("Loon/rule/Loon_GoogleIP.list", clash_and_loon)
    write_rules("QuantumultX/rule/QX_GoogleIP.list", quantumult_x)


if __name__ == "__main__":
    try:
        update_rules()
    except (OSError, ValueError) as error:
        sys.exit(f"Google IP sync failed: {error}")
